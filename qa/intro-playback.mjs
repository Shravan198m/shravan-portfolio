// Run: node qa/intro-playback.mjs [path-to-playwright-module]
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
const { chromium } = await import(process.argv[2] ? pathToFileURL(path.resolve(process.argv[2])).href : 'playwright');
const base = process.env.INTRO_TEST_URL || 'http://127.0.0.1:4174';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const checks = [];
const check = (name, condition) => { assert.ok(condition, name); checks.push(name); };
await mkdir('tmp/intro-qa', { recursive: true });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
  const page = await context.newPage();
  const errors = [];
  const requests = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => requests.push(r.url()));
  await page.goto(base);
  await page.waitForSelector('#enter-sound');
  check('Opening gate is visible', await page.locator('#film-gate').isVisible());
  check('Video is not downloaded before pressing Play', !requests.some(u => /intro-photographic-v3.*\.mp4/.test(u)));
  await page.click('#enter-sound');
  await page.waitForFunction(() => document.querySelector('#opening-film-video').currentTime > 2);
  const media = await page.$eval('#opening-film-video', v => ({ width: v.videoWidth, time: v.currentTime, muted: v.muted, paused: v.paused, audioBytes: v.webkitAudioDecodedByteCount, frames: v.getVideoPlaybackQuality().totalVideoFrames }));
  check('Picture decodes and advances with sound enabled', media.width >= 960 && media.frames > 10 && !media.muted && !media.paused);
  check('Embedded audio is decoded', media.audioBytes > 0);
  check('Separate intro audio is stopped', await page.locator('#intro-score-audio').evaluate(a => a.paused));
  check('Narration caption follows media time', await page.locator('#film-caption').isVisible());
  await page.screenshot({ path: 'tmp/intro-qa/desktop.png' });
  await page.click('#film-pause');
  const pausedAt = await page.$eval('#opening-film-video', v => v.currentTime);
  await page.waitForTimeout(400);
  check('Pause holds picture and embedded sound', Math.abs(await page.$eval('#opening-film-video', v => v.currentTime) - pausedAt) < .05);
  await page.click('#film-pause');
  await page.waitForFunction(t => document.querySelector('#opening-film-video').currentTime > t + .25, pausedAt);
  check('Resume continues from the paused position', true);
  await page.click('#film-mute');
  check('Mute controls the actual video soundtrack', await page.$eval('#opening-film-video', v => v.muted));
  await page.click('#skip-intro');
  await page.waitForFunction(() => document.querySelector('#cinema-intro').hidden);
  check('Skip restores portfolio interaction and stops video', await page.evaluate(() => !document.querySelector('#room').inert && document.querySelector('#opening-film-video').paused));
  await page.click('#replay-intro');
  await page.click('#enter-silent');
  await page.waitForFunction(() => document.querySelector('#opening-film-video').currentTime > .2);
  check('Replay starts at the beginning in silent mode', await page.$eval('#opening-film-video', v => v.currentTime < 2 && v.muted));
  await page.$eval('#opening-film-video', v => { v.currentTime = 29.7; });
  await page.waitForFunction(() => document.querySelector('#cinema-intro').hidden);
  check('Film completion returns to the portfolio', true);
  await page.reload();
  check('Returning visitors can skip the gate automatically', await page.locator('#cinema-intro').isHidden());
  await context.close();

  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  const m = await mobile.newPage(); await m.goto(base); await m.click('#enter-silent');
  await m.waitForFunction(() => document.querySelector('#opening-film-video').currentTime > .5);
  check('Mobile playback remains inline', await m.$eval('#opening-film-video', v => v.playsInline && v.videoWidth > 0));
  check('Mobile uses the smaller photographic export', await m.$eval('#opening-film-video', v => v.currentSrc.endsWith('intro-photographic-v3-score-mobile.mp4') && v.videoWidth === 1280));
  check('Mobile page has no horizontal overflow', await m.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await m.screenshot({ path: 'tmp/intro-qa/mobile.png' }); await mobile.close();

  const reduced = await browser.newContext({ reducedMotion: 'reduce' });
  const r = await reduced.newPage(); await r.goto(base);
  check('Reduced motion skips the automatic opening gate', await r.locator('#cinema-intro').isHidden()); await reduced.close();

  const failed = await browser.newContext(); const f = await failed.newPage();
  await f.route('**/assets/intro-photographic-v3*.mp4', route => route.abort());
  await f.goto(base); await f.click('#enter-sound');
  await f.waitForFunction(() => /unavailable|could not play/.test(document.querySelector('#entrance-status').textContent));
  check('Missing media shows a recoverable error and a visible gate', await f.locator('#film-gate').isVisible());
  await f.click('#skip-intro'); await f.waitForFunction(() => document.querySelector('#cinema-intro').hidden);
  check('A failed video never traps the visitor', await f.$eval('#room', e => !e.inert)); await failed.close();
  const slow = await browser.newContext(); const s = await slow.newPage();
  await s.route('**/assets/intro-photographic-v3*.mp4', async route => { await new Promise(resolve => setTimeout(resolve, 900)); await route.continue(); });
  await s.goto(base); await s.click('#enter-sound'); await s.click('#skip-intro');
  await s.waitForFunction(() => document.querySelector('#cinema-intro').hidden);
  await s.click('#replay-intro'); await s.click('#enter-silent');
  await s.waitForFunction(() => document.querySelector('#opening-film-video').currentTime > .3);
  check('Skipping a loading attempt does not break the next replay', await s.$eval('#opening-film-video', v => !v.paused && v.muted));
  await slow.close();
  check('No uncaught browser errors', errors.length === 0);
  console.log(JSON.stringify({ passed: checks.length, checks }, null, 2));
} finally { await browser.close(); }
